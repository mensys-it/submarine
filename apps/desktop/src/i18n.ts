/**
 * Formats how long ago a Unix time in seconds was: "just now", "12 s ago", … in the
 * language of `t`. `now` is a parameter so a caller can format several values consistently.
 */
export function formatAgo(t: Texts, unixSeconds: number, now = Date.now() / 1000): string {
  const seconds = Math.max(0, Math.round(now - unixSeconds));
  if (seconds < 3) return t.ago.now;
  if (seconds < 60) return t.ago.seconds(seconds);
  if (seconds < 3600) return t.ago.minutes(Math.floor(seconds / 60));
  return t.ago.hours(Math.floor(seconds / 3600));
}
